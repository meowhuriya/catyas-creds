import { NextRequest, NextResponse } from "next/server";
import { GoogleGenAI, Type } from "@google/genai";

export async function GET() {
  const isConfigured = Boolean(process.env.GEMINI_API_KEY);
  return NextResponse.json({ enabled: isConfigured });
}

export async function POST(req: NextRequest) {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    return NextResponse.json(
      {
        enabled: false,
        error: "GEMINI_API_KEY is not configured in environment.",
      },
      { status: 503 }
    );
  }

  try {
    const body = await req.json();
    const { lessonTitle, notesContent, count = 3 } = body;

    if (!notesContent || typeof notesContent !== "string" || notesContent.trim().length < 10) {
      return NextResponse.json(
        { error: "Insufficient notes provided to draft questions (minimum 10 characters)." },
        { status: 400 }
      );
    }

    const ai = new GoogleGenAI({ apiKey });
    const prompt = `You are a university professor creating rigorous quiz questions based strictly on the following student lecture notes for the lesson "${lessonTitle || 'Lecture'}".
Generate ${count} academic quiz questions (a mix of multiple_choice, multiple_select, and short_answer).
For multiple_choice, provide 4 options and exactly 1 correct answer.
For multiple_select, provide 4 options and 2-3 correct answers.
For short_answer, provide 0-1 options and 1-2 acceptable correct answer phrasing strings.
Provide a clear academic explanation for each question.

Lecture Notes:
"""
${notesContent.slice(0, 10000)}
"""`;

    const response = await ai.models.generateContent({
      model: "gemini-2.5-flash",
      contents: prompt,
      config: {
        responseMimeType: "application/json",
        responseSchema: {
          type: Type.ARRAY,
          items: {
            type: Type.OBJECT,
            properties: {
              prompt: {
                type: Type.STRING,
                description: "Question prompt or academic problem statement",
              },
              type: {
                type: Type.STRING,
                enum: ["multiple_choice", "multiple_select", "short_answer"],
              },
              options: {
                type: Type.ARRAY,
                items: { type: Type.STRING },
                description: "Answer choices for multiple choice or select questions",
              },
              correctAnswers: {
                type: Type.ARRAY,
                items: { type: Type.STRING },
                description: "List of correct answer strings exactly matching an option or expected short answer",
              },
              points: {
                type: Type.INTEGER,
                description: "Points assigned to this question (default 10)",
              },
              explanation: {
                type: Type.STRING,
                description: "Academic rationale explaining why the correct answer is right",
              },
            },
            required: ["prompt", "type", "options", "correctAnswers", "points", "explanation"],
          },
        },
      },
    });

    const text = response.text;
    if (!text) {
      throw new Error("No response generated by Gemini model.");
    }

    const questions = JSON.parse(text);
    return NextResponse.json({
      enabled: true,
      questions,
    });
  } catch (err: unknown) {
    const message = err instanceof Error ? err.message : "Unknown error drafting questions";
    console.error("AI quiz draft error:", message);
    return NextResponse.json({ error: message }, { status: 500 });
  }
}
