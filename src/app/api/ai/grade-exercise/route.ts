import { NextRequest, NextResponse } from "next/server";
import { GoogleGenAI, Type } from "@google/genai";
import {
  GradeExerciseRequestSchema,
  GradeExerciseResult,
} from "@/types/mastery-gamification";

export async function GET() {
  const isConfigured = Boolean(process.env.GEMINI_API_KEY);
  return NextResponse.json({ enabled: isConfigured, model: "gemini-2.5-flash" });
}

export async function POST(req: NextRequest) {
  try {
    const rawBody = await req.json();
    const parsed = GradeExerciseRequestSchema.safeParse(rawBody);

    if (!parsed.success) {
      return NextResponse.json(
        { error: parsed.error.errors[0]?.message || "Invalid grading parameters" },
        { status: 400 }
      );
    }

    const {
      prompt,
      rubric,
      modelAnswer,
      topicTitle,
      userTextAnswer,
      userImageBase64,
      imageMimeType,
    } = parsed.data;

    const apiKey = process.env.GEMINI_API_KEY;

    // Graceful fallback if no GEMINI_API_KEY (Demo Mode)
    if (!apiKey) {
      const mockResult = generateMockGradeResult(userTextAnswer, userImageBase64);
      return NextResponse.json(mockResult);
    }

    const ai = new GoogleGenAI({ apiKey });
    const contents: any[] = [];

    const promptText = `You are an expert university examiner evaluating a First-Year B.Tech Computer Science student's solution to an open-ended synthesis challenge.

TOPIC: "${topicTitle || 'CSE Topic'}"
QUESTION PROMPT:
"""
${prompt}
"""

GRADING RUBRIC (Maximum 12 Points):
"""
${rubric}
"""

AUTHORITATIVE MODEL ANSWER:
"""
${modelAnswer}
"""

STUDENT TYPED ANSWER:
"""
${userTextAnswer ? userTextAnswer.slice(0, 5000) : "No text answer typed. Please inspect the attached handwritten image."}
"""

TASK:
1. Carefully inspect the student's solution (from text and/or the uploaded photo of their handwritten notebook work).
2. Assess accuracy step-by-step against the rubric. Award partial credit objectively.
3. Identify any specific algebraic slips, line errors, off-by-one indices, or missing boundary justifications.
4. Calculate 'awardedPoints' (integer between 0 and 12).
5. Calculate 'score' percentage (0 to 100), where awardedPoints / 12 * 100.
6. Set 'isCorrect' to true if awardedPoints >= 9 (>= 75%).
7. Provide constructive pedagogical feedback highlighting both what was executed correctly and exact fixes required.`;

    contents.push({ text: promptText });

    if (userImageBase64) {
      const cleanBase64 = userImageBase64.replace(/^data:[^;]+;base64,/, "");
      contents.push({
        inlineData: {
          mimeType: imageMimeType || "image/jpeg",
          data: cleanBase64,
        },
      });
    }

    const response = await ai.models.generateContent({
      model: "gemini-2.5-flash",
      contents,
      config: {
        responseMimeType: "application/json",
        responseSchema: {
          type: Type.OBJECT,
          properties: {
            isCorrect: {
              type: Type.BOOLEAN,
              description: "True if solution earns >= 75% according to rubric",
            },
            score: {
              type: Type.INTEGER,
              description: "Percentage score (0 to 100)",
            },
            awardedPoints: {
              type: Type.INTEGER,
              description: "Points awarded out of 12 (0 to 12)",
            },
            feedback: {
              type: Type.STRING,
              description: "Examiner feedback summarizing strengths and corrections",
            },
            lineErrors: {
              type: Type.ARRAY,
              items: { type: Type.STRING },
              description: "Specific lines, derivations, or indices with errors",
            },
            stepByStepAnalysis: {
              type: Type.STRING,
              description: "Step-by-step breakdown of how points were awarded",
            },
          },
          required: ["isCorrect", "score", "awardedPoints", "feedback"],
        },
      },
    });

    const text = response.text;
    if (!text) {
      throw new Error("No grading response generated by Gemini model.");
    }

    const result = JSON.parse(text) as GradeExerciseResult;
    return NextResponse.json(result);
  } catch (err: unknown) {
    const message = err instanceof Error ? err.message : "Error grading exercise";
    console.error("grade-exercise route error:", message);
    return NextResponse.json({ error: message }, { status: 500 });
  }
}

function generateMockGradeResult(
  userTextAnswer?: string,
  userImageBase64?: string
): GradeExerciseResult {
  const hasContent = Boolean(
    (userTextAnswer && userTextAnswer.trim().length > 15) || userImageBase64
  );

  if (!hasContent) {
    return {
      isCorrect: false,
      score: 25,
      awardedPoints: 3,
      feedback: "Answer is incomplete or too brief. Please provide a full derivation or step-by-step code trace.",
      lineErrors: ["Missing inductive step or code body"],
      stepByStepAnalysis: "Base case partially recognized (+3 pts). Derivation step missing (0 pts). Convergence verification missing (0 pts).",
    };
  }

  return {
    isCorrect: true,
    score: 92,
    awardedPoints: 11,
    feedback: "Excellent solution! The base condition is properly stated and the algorithmic state transition steps are rigorous and cleanly formatted.",
    lineErrors: ["Minor: Verify boundary limit when n = 0 to prevent negative index references."],
    stepByStepAnalysis: "Base condition verified (+3 pts). Step-by-step logic accurate and clear (+6 pts). Convergence verification sound (+2 pts). Total: 11/12.",
  };
}
